// Bundles drizzle-kit's SQL migrations into a TS module so the app (which has
// no filesystem access to the repo) and Jest run the exact same migrations.
const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '..', 'src', 'db', 'migrations');
const journal = JSON.parse(
  fs.readFileSync(path.join(dir, 'meta', '_journal.json'), 'utf8'),
);

const migrations = journal.entries.map(e => ({
  tag: e.tag,
  statements: fs
    .readFileSync(path.join(dir, `${e.tag}.sql`), 'utf8')
    .split('--> statement-breakpoint')
    .map(s => s.trim())
    .filter(Boolean),
}));

const out =
  '// Generated by scripts/build-migrations.js. Do not edit.\n' +
  'export const migrations: { tag: string; statements: string[] }[] = ' +
  JSON.stringify(migrations, null, 2) +
  ';\n';

fs.writeFileSync(path.join(__dirname, '..', 'src', 'db', 'migrations.generated.ts'), out);
console.log(`Bundled ${migrations.length} migration(s)`);
